# books   = {"파이썬입문": 2, "자료구조": 1, "알고리즘": 0,

#            "운영체제": 3, "네트워크": 1}

# members = {"철수": [], "영희": []}      # 회원별 대출 목록

#

# [입력 형식]

#   input("메뉴(1.대출 2.반납 3.회원조회 4.도서목록 5.종료) : ")

#   메뉴 1,2 : input("회원명 : ")  후  input("도서명 : ")

#   메뉴 3   : input("회원명 : ")

#   메뉴 4   : 추가 입력 없음

#   5를 입력할 때까지 반복

#

# [조건]

#   - 없는 회원 / 없는 도서는 KeyError 로 처리

#   - 재고가 0이면 raise ("대출 불가")

#   - 한 회원은 동시에 최대 3권까지만 대출 가능 (초과 시 raise)

#   - 이미 빌린 책을 또 빌리면 raise

#   - 빌리지 않은 책을 반납하면 raise

#   - 검사 순서는 [회원 → 도서 → 중복대출 → 3권한도 → 재고] 로 할 것

#   - 어떤 입력에도 프로그램이 멈추면 안 됨

#

# [출력 형식]

#   성공 : "대출 완료 : 파이썬입문 (남은 재고 1)"

#          "반납 완료 : 파이썬입문 (남은 재고 2)"

#   오류 : "등록되지 않은 회원입니다"

#          "등록되지 않은 도서입니다"

#          "재고가 없어 대출할 수 없습니다"

#          "최대 3권까지만 대출할 수 있습니다"

#          "이미 대출 중인 도서입니다"

#          "대출하지 않은 도서입니다"

#   회원조회 : "철수 : 파이썬입문, 자료구조 (2권)"

#   도서목록 : "파이썬입문 : 1권"  형태로 한 줄씩

#   종료 시 : 전체 대출 현황 + "미반납 도서 : 3권"

#

# [필요한 함수 : 5개]

#   (1) 메뉴 번호를 받아내는 함수

#   (2) 대출을 처리하는 함수

#   (3) 반납을 처리하는 함수

#   (4) 회원의 대출 현황을 출력하는 함수

#   (5) 전체 도서 현황을 출력하는 함수

#

# [실행 예시]

#   메뉴(1.대출 2.반납 3.회원조회 4.도서목록 5.종료) : 1

#   회원명 : 철수

#   도서명 : 알고리즘

#   재고가 없어 대출할 수 없습니다
