def to_int(value, default=0):
    # 문자열을 정수로 바꾼다. 실패하면 default를 돌려준다
    # value : 바꿀 값
    # default : 실패했을 때 대신 돌려줄 값 (기본 0)
    try:
        # str(value) 로 한번 감싼 이유
        # value에 숫자나 None이 들어와도 에러없이 처리하기 위해서
        # None.strip()은 에러가 나지만 str(None).strip()은 'None'가 됩니다
        return int(str(value).strip())  # 공백 제거
    except (ValueError, TypeError):
        # 괄호로 묶으면 여러 에러를 한꺼번에 잡을 수 있다.
        return default


print(to_int("100"))
print(to_int("삼백"))
print(to_int("삼백", -1))


def to_float(value, defalut=0.0):
    # 문자열을 실수로 바꾼다. 실패하면 default로 돌려준다
    try:
        return float(str(value).strip())
    except (ValueError, TypeError):
        return defalut


print(to_float("3.14"))
print(to_float(None))
print(to_float("3.14만원"))

