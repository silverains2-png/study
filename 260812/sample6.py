# [문제 6] 숫자 맞히기 게임

# ------------------------------------------------------

# 정답은 answer = 42 로 미리 정해둔다.

#

# [입력 형식]

#   input("숫자(1~100) : ")  -> 정수 하나

#   정답을 맞히거나 기회를 다 쓸 때까지 반복

#

# [조건]

#   - 1~100 정수만 허용, 아니면 예외 처리 후 재입력

#   - 잘못된 입력과 중복 입력은 시도 횟수에 포함하지 않음

#   - 유효한 시도는 최대 7회. 7회를 다 쓰고도 못 맞히면 raise 로 게임 오버 처리

#   - 이전에 입력한 숫자를 또 넣으면 "이미 시도한 숫자입니다"

#

# [출력 형식]

#   "DOWN (3/7)"  또는  "UP (3/7)"      ← 현재 시도 횟수 / 최대 횟수

#   정답 : "정답입니다! 총 4회 시도"

#   실패 : "게임 오버, 정답은 42 였습니다"

#   종료 시 : "시도한 숫자 : 50 25 37 42"

#

# [필요한 함수 : 3개]

#   (1) 올바른 숫자 하나를 받아내는 함수

#   (2) 정답과 비교해 결과를 반환하는 함수

#   (3) 게임 결과를 출력하는 함수

#

# [실행 예시]

#   숫자(1~100) : 50

#   DOWN (1/7)

#   숫자(1~100) : 50

#   이미 시도한 숫자입니다

#   숫자(1~100) : 25

#   UP (2/7)


