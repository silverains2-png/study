# 체온을 받아 상태를 문자열로 돌려주는 함수를 만드세요.

#   37.5 이상        -> "발열"

#   36.0 이상 37.5 미만 -> "정상"

#   36.0 미만        -> "저체온"

#

# [기대 결과] (아래 temps 5개를 전부 판정)

#   36.5 -> 정상    38.2 -> 발열    35.1 -> 저체온

#   37.0 -> 정상    39.1 -> 발열

#

# -------------------------------------------------------------
temps = [36.5, 38.2, 35.1, 37.0, 39.1]


def state(temp):
    if temp >= 37.5:
        return "발열"
    elif temp >= 36.0:
        return "정상"
    else:
        return "저체온"


for temp in temps:
    print(temp, "->", state(temp))
