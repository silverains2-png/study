# while문 3요소
# 1) 초기화 : 반복에 쓸 변수를 미리 만들어 둔다(i = 1)
# 2) 조건식 : 언제까지 반복될지 정한다 (while i <= 5)
# 3) 변화식 : 변수를 바꿔서 언젠가 조건을 거짓으로 만든다 (i += 1)
# -> 3번을 빼먹으면 "무한 루프"에 빠집니다. (가장 흔한 실수!!)

