# 평균 구하는 함수
def get_avg(scores):
    # 점수 리스트의 평균 (소수 첫째 자리)
    return round(sum(scores) / len(scores))


# 등급 구하는 함수
def get_grade(score):
    # 평균을 등급으로 바꾼다
    if score >= 90:
        return "A"
    if score >= 80:
        return "B"
    return "C"


def print_std(sub, scores):
    # 과목 성적표 한 줄 출력
    avg = get_avg(scores)
    grade = get_grade(avg)
    print(f"{sub} 평균 : {avg} / 등급 : {grade}")


print_std("국어", kor)
print_std("영어", eng)
print_std("수학", math)

