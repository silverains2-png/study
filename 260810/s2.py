# [수학]                      [파이썬]
# f(x) = 2x + 1               def f(x):
#         |                       return 2*x + 1
#         |                         |
#         7                         7
# 수학에서 x에 3을 대입한다 -> 파이썬에서 f(3)을 호출한다.
#
#
# f(x) = 2x + 6               def f(x):
#                                 return 2*x + 6
#
# def f(score, name, grade):  # score, name, grade <- '매개변수'

# f(x) = 2x + 1
def f(x):
    # f(x) = 2x + 1  : 일차함수
    return 2 * x + 1


print(f(4))  # 9
print(f(10))  # 21

# 주의 : 파이썬에서 곱셈 기호(*)는 생략할 수 없습니다.
# 수학 : 2x   파이썬 : 2*x (2x라고 쓰면 에러)
# 수학 : x^2  파이썬 : x**2 (x^2는 파이썬에서 다른 뜻)

# -----------------------------------------
# return과 print는 다르다
# -----------------------------------------
# return : 계산 결과를 "값으로 돌려준다" -> 다시 계산에 쓸 수 있음
# print : 화면에 "보여주기만 한다" -> 값이 남지 않음


def good(x):
    return 3 * x


def bad(x):
    print(3 * x)


a = good(5)  # 15 가 a라는 변수에 저장
b = bad(5)  # 15 가
c = bad(7)  # 21

print(a)  # 15 가 출력
print(b)  # None : 돌려줄 값이 없다

# 수학으로 비유하면
# return 있는 함수 = 진짜 함수 f(x) -> f(2) -> f(3) 계산가능
# print만 있는 함수 = 칠판에 답만 써놓은 것 -> 다시 쓸 수 없음

# -----------------------------------------
# 함숫값 표 만들기 (while문 복습!)
# -----------------------------------------
# 수학시간에 손으로 그리던 그 표를 코드로 만들어 봅시다

print("x   |  f(x)")
print("----*------")

x = -3
while x <= 3:
    print(f"{x:3} | {f(x):4}")  # :3, :4 -> 칸맞추기 : 앞에 몇칸 비울지
    x += 1
# x가 1씩 커질때 f(x)는 얼마씩 커지나요?
# -> 항상 2씩 = 이게 바로 '기울기'

# -----------------------------------------
# y = ax - b
# -----------------------------------------
# a, b 인자로 받으면 "모든 일차함수"를 하나의 함수로 표현할 수 있습니다


def linear(a, b, x):
    # y = ax + b 의 함수값
    # a : 기울기, b : y절편
    return a * x + b


print("y = 2x + 1 에서 x = 4 ->", linear(2, 1, 4))  # 값이 바로 튀어나옴 : 9
print("y = -3x + 5 에서 x = 2 ->", linear(-3, 5, 2))  # -1

# -----------------------------------------
# 기울기와 y절편 구하기
# -----------------------------------------
# 두 점 (x1, y1) , (x2, y2)를 지나는 직선의 기울기
# a = y의 변화량 / x의 변화량 = (y2 - y1) / (x2 - x1)


# 기울기를 구하는 모델
def line(x1, y1, x2, y2):
    # 두 점을 지나는 직선의 기울기
    return (y2 - y1) / (x2 - x1)


def line_y(x1, y1, x2, y2):
    # 두 점을 지나는 직선의 식을 구해서 (기울기, y절편)을 돌려준다
    a = line(x1, y1, x2, y2)
    b = y1 - a * x1
    return a, b


# 두점 (1, 3) (4, 9)을 지나는 직선

print(line(1, 3, 4, 9))  # 2.0
print(line_y(1, 3, 4, 9))  # (2.0, 1.0)

# x절편 구하기 : (y = 0)이 되는 x
# x = -b / a


def line_x(a, b):
    # y = ax + b 의 x절편
    if a == 0:
        return None  # 기울기가 0 이면 x축과 수평이므로 x절편이 없음
    return -b / a


print("y = 2x + 1의 x절편", line_x(2, 1))  # -0.5
print("y = 3의 x절편", line_x(0, 3))  # None

