og = [3, 1, 2]


def sort_bad(data):  # 지역변수긴 한데
    data.sort()  # 애초에 원본을 건드리는 함수를 쓰면 -> 원본을 건드린다!
    return data


def sort_good(data):
    new_data = sorted(data)
    return new_data


result = sort_good(og)
print("sort_good 후 원본 : ", og, "결과 : ", result)  # [3, 1, 2] [1, 2, 3]

result = sort_bad(og)
print("sort_bad 후 원본 : ", og, "결과 : ", result)  # [1, 2, 3] [1, 2, 3]

