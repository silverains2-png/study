# ------------------------------------------------------

# [문제 3] 과목별 성적 입력기

# ------------------------------------------------------

# 학생 3명의 국어·영어·수학 점수를 입력받아 성적표를 만드시오.

#

# [입력 형식]

#   학생 1명당

#     input("이름 : ")      -> 문자열 (빈 값이면 다시 입력)

#     input("국어 : ")      -> 정수

#     input("영어 : ")      -> 정수

#     input("수학 : ")      -> 정수

#   위 과정을 3명 반복 (재입력 제외하면 최소 12번 입력)

#

# [조건]

#   - 점수는 0~100 정수만 허용, 범위를 벗어나면 raise 로 예외 발생

#   - 잘못 입력하면 그 과목만 다시 입력 (앞 과목 점수는 유지)

#   - 같은 과목에서 3번 연속 틀리면 0점 처리 후 다음 과목으로

#   - 학점 : 90↑A / 80↑B / 70↑C / 60↑D / 나머지 F

#   - 과목별 평균은 중첩 반복문으로 계산

#

# [출력 형식]

#   오류 시 : "0~100 사이만 가능합니다 (남은 기회 2회)"

#             "숫자만 입력하세요 (남은 기회 1회)"

#             "3회 모두 실패, 0점 처리합니다"

#   마지막 :

#     "이름   평균    학점"

#     "철수   88.33   B"

#     "[과목별 평균] 국어 : 85.00 / 영어 : 77.00 / 수학 : 90.00"

#

# [필요한 함수 : 3개]

#   (1) 과목 하나의 점수를 받아내는 함수 (재입력·3회 제한 포함)

#   (2) 평균을 받아 학점을 반환

#   (3) 전체 성적표를 출력

#

# [실행 예시]

#   이름 : 철수

#   국어 : 150

#   0~100 사이만 가능합니다 (남은 기회 2회)

#   국어 : 90


