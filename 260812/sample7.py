# [문제 7] 수식 계산기 (한 줄 입력)

# ------------------------------------------------------

#

# [입력 형식]

#   input("수식 입력(종료: exit) : ")  -> "숫자 연산자 숫자" 형태, 공백 구분

#   exit 입력 시 종료

#   예) 8 + 2    /    10 // 3

#

# [조건]

#   - 공백으로 나눈 개수가 3개가 아니면 예외 처리

#   - 지원 연산자 : +  -  *  /  //  %  (그 외에는 raise)

#   - 0으로 나누기( / , // , % 모두 ) 처리

#   - 소수 입력 허용, 단 //  와 %  는 정수만 허용(아니면 raise)

#     ※ 정수 판별은 입력 문자열에 "." 이 있는지 보거나,

#       float 로 바꾼 뒤 int 로 바꾼 값과 같은지 비교하면 된다

#   - finally 로 매 계산마다 구분선 출력

#

# [출력 형식]

#   성공 : "결과 : 10.00"

#   오류 : "숫자 연산자 숫자 형태로 입력하세요"   (값이 3개가 아닐 때)

#          "숫자를 입력하세요"                    (연산자는 맞지만 숫자가 아닐 때)

#          "지원하지 않는 연산자입니다"

#          "0으로 나눌 수 없습니다"

#          "// 와 % 는 정수만 가능합니다"

#   매번 : "--------"

#   종료 시 : "최댓값 : 10.00"  (계산 성공이 없으면 "계산 기록이 없습니다")

#

# [필요한 함수 : 2개]

#   (1) 수식 문자열을 (숫자, 연산자, 숫자) 로 분해

#   (2) 세 값을 받아 계산 결과를 반환

#

# [실행 예시]

#   수식 입력(종료: exit) : 8 // 2.5

#   // 와 % 는 정수만 가능합니다

