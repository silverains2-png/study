# 2. 변수는 언제든 값을 바꿀 수 있다 (그래서 '변'수)
# ------------------------

score = 99  # 처음에는 9
score = 100  # 나중에 100으로 덮어씀
print(score)  # 100

# 자기 자신을 이용해서 바꾸기
count = 10  # 처음에 10을 넣었음
count = count + 5  # 오른쪽 먼저 계산(10 + 5 = 15)

# count = count + 25  # 40 : 진짜 위에서 부터 순서대로 계산한다! (10 > 15 > 40)
# print(count) = 40
print(count)  # 15

# 위와 똑같은 뜻인데 더 짧게 쓰는 방법(복합 대입 연산자)
count += 5  # count = count + 5 -> 20  >>>  2개 같은의미!!
print(count)
count -= 3  # count = count - 3 -> 17
print(count)
count *= 2  # count = count * 2 -> 34
print(count)
count /= 2  # count = count / 2 -> 17.0 (나누기는 결과가 실수이다!)

print(count)  # 17.0

