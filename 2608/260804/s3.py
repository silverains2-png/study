numbers = [30, 10, 50, 20]
numbers.sort()  # 원본을 정렬 (돌려주는 값 없음)
print(numbers)  # [10, 20, 30, 50]

numbers.sort(reverse=True)  # 내림차순
print(numbers)  # [50, 30, 20, 10]

original = [30, 10, 20, 50]
result = sorted(original)  # 새 리스트를 돌려줌 : 원본을 건드리지 않는다!
