i = 1  # 1) 초기화
while i <= 5:  # 2) 조건식
    print(i)
    i += 1  # 3) 변화식

# ------------------------------------
# 거꾸로 세기
# ------------------------------------

count = 5
while count >= 1:
    print(count)
    count -= 1

# ------------------------------------
# break : 반복문 즉시 끝내기
# ------------------------------------

num = 1
while num <= 100:
    print(num)  # num == 6 까지 찍힘
    if num > 5:
        break  # num == 6 이 되면 탈출 -> while 종료
    print(num)  # num == 5 까지 찍힘 -> 위에 if 문에서 num > 5 break에서 종료됨
    num += 1

# ------------------------------------
# continue - 이번 회차만 건너뛰기
# ------------------------------------

k = 0
while k < 10:
    k += 1  # continue 앞에 변화식을 두는게 안전합니다
    if k % 2 == 0:  # 짝수면
        continue  # 아래 print를 건너뛰고 조건식으로 돌아감
    print(k)

# 만약 k += 1 을 print 아래에 뒀다면?
# 짝수에서 continue -> k가 안늘어남 -> 무한 루프

# ------------------------------------
# while True + break (가장 실무에서 많이쓰는 형태)
# ------------------------------------

password = "1234"
tries = 0
while True:
    tries += 1
    pss = input("비밀번호를 입력해 주세요 : ")
    if pss == password:
        print(f"{tries}번째 시도 : 성공!")
        break
    print(f"{tries}번째 시도 : 실패")

# ------------------------------------
# while - else (파이썬에만 있는 문법)
# ------------------------------------
# break 없이 조건이 거짓이 되어 정상 종료됐을 때만 else가 실행

x = 1

while x <= 3:
    print("반복중 : ", x)
    x += 1
else:
    print("break 없이 정상 종료됨 -> else 실행")

# ------------------------------------
# 누적 & 조건 조합 - 2의 거듭제곱
# ------------------------------------
# 1000을 처음 넘는 2의 거듭제곱 찾기

value = 1
power = 0

while value <= 1000:
    value *= 2
    power += 1

print(f"2^{power} = {value}")

# ------------------------------------
# for문과 뭐가 다를까?
# ------------------------------------
# for : 반복 횟수를 "이미 알고 있을 때" (리스트, range() 등)
# while : 반복 횟수를 "모를 때" (조건이 만족될 때까지)

for i in range(1, 4):
    print("for", i)

i = 1
while i < 4:
    print("while", i)
    i += 1

