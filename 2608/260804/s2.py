# ----------------------------------------
# 4. if- elif - else :  갈림길이 여러개인 경우
# ----------------------------------------

score = 85

if score >= 90:  # 참 인지 확인 : X
    print("A등급")
elif score >= 80:  # 참 인지 확인 : O -> 멈춤
    print("B등급")  # 출력하고 종료
elif score >= 70:
    print("C등급")
else:
    print("F등급")

# ---- 핵심 : 위에서부터 검사하고, 하나가 걸리면 나머지는 건너뜁니다 ----
# score = 85 일떄
# 1) score >= 90 ? -> False, 다음으로
# 2) score >= 80 ? -> True , 실행하고 조건문 전체를 빠져나감
# 3) score >= 70 은 검사조차 하지 않음 (참이지만 무시됨)

# ---- 그래서 순서가 매우 중요합니다 ----

score = 95
if score >= 70:  # 가장 느슨한 조건을 위에 두면
    print("C등급")  # 95점인데 C등급이 나옴!!
elif score >= 90:
    print("A등급")  # 여기까지 오지도 못함!!

# 규칙 : 좁은(까다로운) 조건부터 위에 쓰세요

# ---- elif는 몇개든 쓸 수 있고, else는 생략이 가능합니다 ----

