def safe_pass(pw):
    "8자 이상 + 숫자 포함 + 영문자 포함이면 True"
    if len(pw) < 8:
        return False
    if not any(ch.isdigit() for ch in pw):
        return False
    if not any(ch.isalpha() for ch in pw):
        return False
    return True


while True:
    pw = input("비밀번호를 입력하세요 : ")
    if safe_pass(pw):
        print("사용할 수 있는 비밀번호 입니다")
        break
    else:
        print("사용할 수 없는 비밀번호 입니다 다시 입력해주세요")

