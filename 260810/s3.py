def discount(p):
    # 20% 할인가
    return int(p * 8)


# 할인을 하고 부가세를 붙이는 함수
def f_price(p):
    return tax(discount(p))  # 안쪽 discount가 먼저 실행됨


print("원가 50000원")
print("할인만 : ", discount(50000))
print("부가세만 : ", tax(50000))
print("할인 후 부가세 : ", f_price(50000))

