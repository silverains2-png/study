# [문제 2] 장바구니 만들기


# 상품 이름을 계속 입력받아 리스트에 담으세요.

# "그만"을 입력하면 반복 종료 → 담긴 상품 전체와 총 개수 출력.

# 아무것도 안 담았으면 "장바구니가 비었습니다" 출력.


# 실행 예시)

#   상품 입력(그만: 종료): 우유

#   상품 입력(그만: 종료): 계란

#   상품 입력(그만: 종료): 그만

#   장바구니: ['우유', '계란'] / 총 2개

cart = []

while True:
    item = input("상품 입력(그만 : 종료) : ")

    if item == "그만":
        if not cart:
            print("장바구니가 비었습니다")
        else:
            print(f"장바구니 : {cart} / 총 {len(cart)}개")
        break
    else:
        cart.append(item)
