# 1~10 사이의 숫자 3개를 입력받아 합계를 구하시오.

# [입력 형식]
#   input("숫자(1~10) : ")
#   올바른 값 3개를 모을 때까지 계속 반복 (while 문 사용)

# [조건]
#   - 숫자가 아니면 다시 입력받기
#   - 1~10 밖이면 다시 입력받기
#   - 잘못 넣은 것은 개수에 포함하지 않음

# [출력 형식]
#   오류 : "숫자를 입력하세요"
#          "1~10 사이만 가능합니다"
#   마지막 : "입력한 숫자 : [3, 7, 5]"
#            "합계 : 15"

# [필요한 함수 : 1개]
#   (1) 올바른 숫자 하나를 받아 반환 (재입력 반복 포함)

# [실행 예시]
#   숫자(1~10) : abc
#   숫자를 입력하세요
#   숫자(1~10) : 50
#   1~10 사이만 가능합니다
#   숫자(1~10) : 3
#   숫자(1~10) : 7
#   숫자(1~10) : 5
#   입력한 숫자 : [3, 7, 5]
#   합계 : 15

numbers = []


def collect_number():
    while True:
        num = input("숫자(1~10) : ")

        try:
            num = int(num)
            if 1 <= num <= 10:
                return num
            else:
                print("1~10 사이만 가능합니다")
        except ValueError:
            print("숫자를 입력하세요")


while len(numbers) < 3:
    numbers.append(collect_number())

print(f"입력한 숫자 : {numbers}")
print(f"합계 : {sum(numbers)}")
