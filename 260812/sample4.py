# 좌표를 입력받아 해당 위치의 값을 출력하시오.

#

# [입력 형식]

#   input("좌표 입력(행 열) : ")  -> 한 줄에 두 개, 공백으로 구분

#   빈 줄(엔터만)을 입력하면 종료

#   ※ 종료 검사를 split() 보다 먼저 해야 한다 (빈 줄은 나누면 0개라 오류로 새어 나감)

#   예) 1 2

#

# [조건]

#   - 공백으로 나눈 개수가 2개가 아니면 예외 처리

#   - 숫자가 아니면 예외 처리

#   - 범위를 벗어나면 IndexError 를 잡아 처리, 음수 인덱스도 오류로 볼 것

#   - 성공 시 그 값이 속한 행의 합과 열의 합도 함께 출력

#

# [출력 형식]

#   성공 : "값 : 6 / 행 합 : 15 / 열 합 : 18"

#   실패 : "행과 열 2개를 입력하세요"

#          "숫자를 입력하세요"

#          "범위를 벗어났습니다"

#   종료 시 : "성공 3회 / 오류 2회"

#

# [필요한 함수 : 3개]

#   (1) 입력 문자열을 (행, 열) 로 변환 (문제가 있으면 예외 발생)

#   (2) board 와 좌표를 받아 값을 반환

#   (3) 행 합과 열 합을 반환

#

# [실행 예시]

#   좌표 입력(행 열) : 1 2

#   값 : 6 / 행 합 : 15 / 열 합 : 18

#   좌표 입력(행 열) : 5 0

#   범위를 벗어났습니다


