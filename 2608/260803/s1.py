# 1. 변수란?
# 변수 = 값에 붙이는 "이름표"
# 값을 메모리에 저장해 두고, 나중에 그 이름으로 다시 꺼내 쓰는것
# ------------------------

age = 25
# age -> 변수명(이름표)
# = -> 대입 연산자(=) : "오른쪽의 값을 왼쪽 이름에 넣어라"
# 25 -> 값(value) : 실제로 저장되는 데이터

print(age)  # 25 <- 이름을 부르면 값이 나옴

# 주의 : 수학의 '='(같다)가 아니라 '넣는다'라는 뜻!!
# 같은지 비교할때는 '=='를 쓴다!

