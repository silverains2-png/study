# [입력 형식]

#   input("데이터 입력(이름,과목,점수) : ")  -> 쉼표로 구분된 한 줄

#   빈 줄(엔터만)을 입력하면 입력 종료

#   예) 철수,수학,90

#

# [조건]

#   - 쉼표로 나눈 개수가 3개가 아니면 예외 처리

#   - 점수가 숫자가 아니거나 0~100 밖이면 예외 처리

#   - 같은 사람의 같은 과목이 또 들어오면 raise ("중복 입력")

#   - 정상 데이터는 {이름: {과목: 점수}} 중첩 딕셔너리에 저장

#   - 오류가 난 줄은 줄 번호와 사유를 모아 마지막에 출력

#   - 과목별 통계는 중첩 반복문으로 계산

#

# [출력 형식]

#   오류 발생 시 즉시 : "2번째 줄 오류 - 중복 입력"

#   ※ 줄 번호는 오류 난 줄까지 포함해서 센다 (1부터 시작)

#   마지막 : (아래는 위 실행 예시에 데이터를 더 넣었을 때의 결과 예시)

#     "[학생별]"

#     "철수 : 수학 90, 영어 80 / 평균 85.00"

#     "[과목별]"

#     "수학 : 2명 / 평균 85.00"

#     "[오류 목록]"

#     "2번째 줄 - 중복 입력"

#

# [필요한 함수 : 3개]

#   (1) 한 줄을 파싱해 (이름, 과목, 점수) 반환

#   (2) 데이터를 딕셔너리에 저장 (중복이면 예외 발생)

#   (3) 최종 결과를 출력

#

# [실행 예시]

#   데이터 입력(이름,과목,점수) : 철수,수학,90

#   데이터 입력(이름,과목,점수) : 철수,수학,80

#   2번째 줄 오류 - 중복 입력

#   데이터 입력(이름,과목,점수) : 영희,영어,백점

#   3번째 줄 오류 - 점수는 숫자여야 합니다


