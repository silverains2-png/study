# 4. 잘라내기 - 슬라이싱
# -------------------------------------------------

number = [10, 20, 30, 40, 50]
print(number[1:3])  # [20, 30] : 끝번호는 포함 안된다!
print(number[:3])  # [10, 20, 30] : 처음부터 끝번호 전까지
print(number[2:])  # [30, 40, 50] : 2번 다음부터 끝까지
print(number[-2:])  # [40, 50] : 뒤에서 2번째부터 끝까지
print(number[::2])  # [10, 30, 50] : 하나걸러 하나

# 꿀팁 [::-1] 이면 뒤집힙니다
print(number[::-1])  # [50, 40, 30, 20, 10]
# reverse()와 달리 원본을 건드리지 않고 새 리스트를 만듬
