# ------------------------------------------------------

# [문제 8] 은행 계좌 시스템

# ------------------------------------------------------

# account = {"철수": 10000, "영희": 5000}

#

# [입력 형식]

#   input("메뉴(1.입금 2.출금 3.이체 4.조회 5.종료) : ")

#   메뉴 1,2 : input("계좌명 : ")  후  input("금액 : ")

#   메뉴 3   : input("보내는 사람 : ") → input("받는 사람 : ") → input("금액 : ")

#   메뉴 4   : input("계좌명 : ")

#   5를 입력할 때까지 반복

#

# [조건]

#   - 없는 계좌명은 KeyError 로 처리

#   - 금액이 숫자가 아니거나 0 이하면 예외 처리

#   - 출금액 > 잔액 이면 raise ("잔액 부족")

#   - 1회 출금 한도 5000원, 초과 시 raise

#     ※ 검사 순서는 반드시 [한도 → 잔액] 으로 할 것

#       (둘 다 걸리는 경우 한도 메시지가 나와야 한다)

#   - 이체 시 보내는 사람과 받는 사람이 같으면 raise

#   - 이체는 반드시 검사를 모두 통과한 뒤에 차감할 것 (돈이 사라지면 안 됨)

#   - 성공한 거래는 내역 리스트에 저장

#

# [출력 형식]

#   성공 : "입금 완료 / 잔액 : 15000"

#          "출금 완료 / 잔액 : 5000"

#          "이체 완료 / 철수 잔액 : 7000, 영희 잔액 : 8000"

#   조회 : "철수 잔액 : 7000"

#   오류 : "존재하지 않는 계좌입니다"

#          "금액은 숫자여야 합니다"

#          "금액은 0보다 커야 합니다"

#          "잔액이 부족합니다"

#          "1회 출금 한도(5000원)를 초과했습니다"

#          "같은 계좌로는 이체할 수 없습니다"

#   종료 시 : 거래 내역을 한 줄씩 출력

#             예) "입금 철수 5000"  /  "이체 철수→영희 3000"

#   ※ 위 출력 예시들은 각각 독립적인 상황이라 잔액이 서로 이어지지 않는다

#

# [필요한 함수 : 4개]

#   (1) 계좌명을 확인하는 함수

#   (2) 금액을 받아내는 함수

#   (3) 이체를 처리하는 함수

#   (4) 거래 내역을 출력하는 함수

#

# [실행 예시]

#   메뉴(1.입금 2.출금 3.이체 4.조회 5.종료) : 3

#   보내는 사람 : 철수

#   받는 사람 : 철수

#   같은 계좌로는 이체할 수 없습니다


