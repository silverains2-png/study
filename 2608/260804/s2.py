# 5. if를 여러개 쓰는것 vs elif를 쓰는것
# ----------------------------------------
# 겉보기엔 비슷하지만 동작이 완전히 다르다!

number = 15

# ---- elif : 하나만 실행 ----
if number > 10:  # True
    print("10보다 큼")  # 실행
elif number > 5:  # 실행 안된다
    print("5보다 큼")

# ---- if 두개 : 각각 따로 검사 -> 둘 다 실행될 수 있음
if number > 10:
    print("10보다 큼")  # 실행

if number > 5:
    print("5보다 큼")  # 실행

# 언제 뭘 쓰나?
# 등급 판정처럼 '하나만 골라'야 하면 -> elif
# 조건들이 서로 독립적이면(각각 검사) -> if 여러개

