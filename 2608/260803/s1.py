# 12. (심화) 변수는 값을 '담는 상자'가 아니라 값을 '가리키는 화살표'
# ------------------------

a = [1, 2, 3]  # list를 만들고, a가 그것을 가리킴
b = a  # b도 '같은' 리스트를 가리킴 (복사가 아님!!)

b.append(4)  # b를 통해 리스트를 수정하면
print(a)  # [1, 2, 3, 4] <- a로 봐도 바뀌어 있다 (같은 것이니까) >> 복사의 개념이 아님

# 숫자 문자열은 값을 바꿀 수 없어서 이런 현상이 안생김.

